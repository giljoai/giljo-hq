<script setup>
import { ref, computed, watch, onMounted, onUnmounted } from 'vue'
import { useProductStore } from '@/stores/products'
import { buildRoadmapPrompt as buildRoadmapPromptText } from '@/content/roadmap/prompts'
import { useProjectStore } from '@/stores/projects'
import { useWebSocketStore } from '@/stores/websocket'
import { useSequenceRunStore } from '@/stores/sequenceRunStore'
import { registerReconnectResync } from '@/stores/websocketEventRouter'
import api from '@/services/api'
import { parseErrorResponse } from '@/utils/errorMessages'
import { agentSavedAfter, waitIsSuperseded } from '@/utils/roadmapWaitReconcile'
import { useToast } from '@/composables/useToast'
import { useTaskCrud } from '@/composables/useTaskCrud'
import { useFormatDate } from '@/composables/useFormatDate'
import draggable from 'vuedraggable'
import RoadmapCard from '@/components/RoadmapCard.vue'
import BaseDialog from '@/components/common/BaseDialog.vue'
import RoadmapPromptActions from '@/components/roadmap/RoadmapPromptActions.vue'
import ProjectCreateEditDialog from '@/components/projects/ProjectCreateEditDialog.vue'
import TaskEditDialog from './tasks/TaskEditDialog.vue'

const productStore = useProductStore()
const projectStore = useProjectStore()
const wsStore = useWebSocketStore()
const sequenceRunStore = useSequenceRunStore()
const { showToast } = useToast()
const { formatDate } = useFormatDate()

const TASK_STATUS_OPTIONS = ['pending', 'in_progress', 'on_hold', 'completed', 'blocked', 'cancelled']

const loading = ref(false)
const noActiveProduct = ref(false)
const roadmap = ref(null)
const items = ref([])
const foldInTasks = ref(true)
const projectTypes = ref([])

const activeProduct = computed(() => productStore.currentProduct)
const viewedProductId = computed(() => productStore.currentProduct?.id)
const isEmptyRoadmap = computed(() => items.value.length === 0)

const showInsightBanner = computed(() => !isEmptyRoadmap.value && !!roadmap.value?.summary)
const insightTitle = computed(() => {
  const at = roadmap.value?.last_generated_at
  return at ? `Why this order · ${formatDate(at)}` : 'Why this order'
})

const displayItems = computed(() =>
  foldInTasks.value ? items.value : items.value.filter((it) => it.item_type !== 'task'),
)

const waiting = ref(false)
const isPersisting = ref(false)
let waitingTimeout = null
let refetchDebounce = null
let unsubRoadmap = null
let unsubAgentActive = null
let unsubProjectUpdate = null
let unsubHeadlessLifecycle = []
let unsubResync = null

const WAITING_TIMEOUT_MS = 150000
const REFETCH_DEBOUNCE_MS = 600

const AGENT_ACTIVE_STORAGE_PREFIX = 'giljo.roadmap.agentActiveAt.'

function agentActiveStorageKey() {
  const pid = productStore.effectiveProductId
  return pid ? `${AGENT_ACTIVE_STORAGE_PREFIX}${pid}` : null
}

function persistAgentActive() {
  const key = agentActiveStorageKey()
  if (!key) return
  try {
    localStorage.setItem(key, String(Date.now()))
  } catch {
    /* localStorage unavailable (private mode / quota) — non-fatal */
  }
}

function clearPersistedAgentActive() {
  const key = agentActiveStorageKey()
  if (!key) return
  try {
    localStorage.removeItem(key)
  } catch {
    /* non-fatal */
  }
}

function startWaiting(durationMs = WAITING_TIMEOUT_MS) {
  waiting.value = true
  if (waitingTimeout) clearTimeout(waitingTimeout)
  waitingTimeout = setTimeout(() => {
    waiting.value = false
    waitingTimeout = null
    clearPersistedAgentActive()
  }, durationMs)
}

function dismissWaiting() {
  waiting.value = false
  if (waitingTimeout) {
    clearTimeout(waitingTimeout)
    waitingTimeout = null
  }
  clearPersistedAgentActive()
}

function rehydrateWaitingFromStorage() {
  if (waiting.value) return
  const key = agentActiveStorageKey()
  if (!key) return
  let raw = null
  try {
    raw = localStorage.getItem(key)
  } catch {
    return
  }
  if (raw === null) return
  const stampedAt = Number(raw)
  if (agentSavedAfter(roadmap.value, items.value, stampedAt)) {
    clearPersistedAgentActive()
    return
  }
  const elapsed = Date.now() - stampedAt
  if (Number.isFinite(stampedAt) && elapsed >= 0 && elapsed < WAITING_TIMEOUT_MS) {
    startWaiting(WAITING_TIMEOUT_MS - elapsed)
  } else {
    clearPersistedAgentActive()
  }
}

function onAgentActive() {
  startWaiting()
  persistAgentActive()
}

const currentPromptText = computed(() =>
  buildRoadmapPrompt(isEmptyRoadmap.value ? 'create' : 'refresh')
)

const REFETCH_UPDATE_TYPES = new Set(['status_changed', 'activated', 'deactivated', 'updated'])

function onProjectUpdated(payload) {
  if (!payload || !REFETCH_UPDATE_TYPES.has(payload.update_type)) return
  onRoadmapUpdated()
}

function onRoadmapUpdated() {
  if (refetchDebounce) clearTimeout(refetchDebounce)
  refetchDebounce = setTimeout(async () => {
    refetchDebounce = null
    if (isPersisting.value) {
      onRoadmapUpdated()
      return
    }
    await fetchRoadmap()
    dismissWaiting()
  }, REFETCH_DEBOUNCE_MS)
}

function buildRoadmapPrompt(mode) {
  const host = typeof window !== 'undefined' ? window.location.host : ''
  return buildRoadmapPromptText(mode, activeProduct.value, host)
}

async function copyToClipboard(text) {
  try {
    if (navigator.clipboard && window.isSecureContext) {
      await navigator.clipboard.writeText(text)
      return true
    }
    throw new Error('insecure-context')
  } catch {
    try {
      const ta = document.createElement('textarea')
      ta.value = text
      ta.style.position = 'fixed'
      ta.style.opacity = '0'
      document.body.appendChild(ta)
      ta.focus()
      ta.select()
      const ok = document.execCommand('copy')
      document.body.removeChild(ta)
      return ok
    } catch {
      return false
    }
  }
}

async function copyRoadmapPrompt(editedText) {
  const mode = isEmptyRoadmap.value ? 'create' : 'refresh'
  const text = typeof editedText === 'string' ? editedText : buildRoadmapPrompt(mode)
  const ok = await copyToClipboard(text)
  if (ok) {
    showToast({
      message: 'Prompt copied — paste it into the agent connected to THIS account.',
      type: 'success',
    })
  } else {
    showToast({
      message: 'Could not copy automatically. Select and copy the prompt manually.',
      type: 'warning',
    })
  }
}

async function fetchRoadmap({ notify = false } = {}) {
  loading.value = true
  try {
    const { data } = await api.roadmap.get(viewedProductId.value)
    noActiveProduct.value = false
    roadmap.value = data.roadmap || null
    items.value = Array.isArray(data.items) ? [...data.items] : []
  } catch (error) {
    if (error.response?.status === 404) {
      noActiveProduct.value = true
      roadmap.value = null
      items.value = []
    } else {
      console.error('[ROADMAP] Failed to load roadmap:', error)
      if (notify) {
        showToast({ message: 'Failed to load the roadmap. Please try again.', type: 'error' })
      }
    }
  } finally {
    loading.value = false
  }
}

function rebuildFullOrder(newVisibleOrder) {
  const visibleIds = new Set(displayItems.value.map((i) => i.id))
  let vi = 0
  return items.value.map((it) => (visibleIds.has(it.id) ? newVisibleOrder[vi++] : it))
}

function onListReorder(newVisibleOrder) {
  persistOrder(rebuildFullOrder(newVisibleOrder))
}

async function demote(item) {
  const arr = [...items.value]
  const from = arr.findIndex((i) => i.id === item.id)
  if (from < 0 || from === arr.length - 1) return
  const [moved] = arr.splice(from, 1)
  arr.push(moved)
  await persistOrder(arr)
}

async function persistOrder(orderedArr) {
  const previous = items.value
  items.value = orderedArr
  isPersisting.value = true
  try {
    const payload = orderedArr.map((it, i) => ({ id: it.id, sort_order: i }))
    await api.roadmap.reorder(payload, viewedProductId.value)
  } catch (error) {
    console.error('[ROADMAP] Failed to persist new order:', error)
    items.value = previous
    showToast({ message: 'Could not save the new order. Please try again.', type: 'error' })
    await fetchRoadmap()
  } finally {
    isPersisting.value = false
  }
}

async function removeItem(item) {
  if (!item?.id) return
  const previous = items.value
  items.value = items.value.filter((it) => it.id !== item.id)
  try {
    await api.roadmap.removeItem(item.id, viewedProductId.value)
    showToast({ message: 'Removed from roadmap', type: 'success' })
  } catch (error) {
    console.error('[ROADMAP] Failed to remove item:', error)
    items.value = previous
    showToast({ message: 'Could not remove from the roadmap. Please try again.', type: 'error' })
  }
}

const projectDialogRef = ref(null)
const showProjectDialog = ref(false)
const editingProject = ref(null)
const showClearMissionDialog = ref(false)

async function openItem(item) {
  if (item.item_type === 'project') {
    await openProject(item)
  } else {
    await openTask(item)
  }
}

async function openProject(item) {
  const full = await projectStore.fetchProject(item.project_id)
  if (!full) {
    showToast({ message: 'Could not load project details. Please try again.', type: 'error' })
    return
  }
  editingProject.value = full
  showProjectDialog.value = true
}

async function onProjectSaved() {
  editingProject.value = null
  await fetchRoadmap({ notify: true })
}

function onClearMissionConfirmed() {
  projectDialogRef.value?.clearMissionData()
  showClearMissionDialog.value = false
}

function onTypeCreated(newType) {
  if (newType) projectTypes.value.push(newType)
}

const {
  showTaskDialog,
  editingTask,
  saving,
  currentTask,
  editTask,
  cancelTask,
  saveTask,
} = useTaskCrud()

const taskTypeOptions = computed(() => {
  const opts = projectTypes.value.map((t) => ({ title: t.abbreviation, value: t.abbreviation }))
  opts.unshift({ title: '—', value: null })
  return opts
})

async function openTask(item) {
  try {
    const { data } = await api.tasks.get(item.task_id)
    editTask(data)
  } catch (error) {
    console.error('[ROADMAP] Failed to load task details:', error)
    showToast({ message: 'Could not load task details. Please try again.', type: 'error' })
  }
}

function onCurrentTaskUpdate(updated) {
  currentTask.value = updated
}

async function onTaskSave(formRef) {
  await saveTask(formRef, () => fetchRoadmap({ notify: true }))
}

const showConvertConfirm = ref(false)
const conversionItem = ref(null)

function convertTask(item) {
  if (!productStore.effectiveProductId) {
    showToast({ message: 'Activate a product before converting tasks.', type: 'warning' })
    return
  }
  conversionItem.value = item
  showConvertConfirm.value = true
}

async function confirmConvert() {
  showConvertConfirm.value = false
  const item = conversionItem.value
  conversionItem.value = null
  if (!item?.task_id) return
  try {
    const { data } = await api.tasks.convertToProject(item.task_id)
    showToast({ message: `Converted to project: ${data.name}`, type: 'success' })
    await fetchRoadmap({ notify: true })
  } catch (error) {
    console.error('[ROADMAP] Failed to convert task:', error)
    showToast({ message: parseErrorResponse(error).message || 'Failed to convert task to project.', type: 'error' })
  }
}

watch(viewedProductId, () => {
  roadmap.value = null
  items.value = []
  fetchRoadmap()
})

onMounted(async () => {
  unsubRoadmap = wsStore.on('roadmap:updated', onRoadmapUpdated)
  unsubAgentActive = wsStore.on('roadmap:agent_active', onAgentActive)
  unsubProjectUpdate = wsStore.on('project_update', onProjectUpdated)
  unsubHeadlessLifecycle = ['project:staging_complete', 'project:implementation_launched'].map((t) => wsStore.on(t, onRoadmapUpdated))
  unsubResync = registerReconnectResync(async () => {
    await Promise.allSettled([sequenceRunStore.hydrate(), fetchRoadmap()])
    if (waitIsSuperseded(roadmap.value, items.value, agentActiveStorageKey())) dismissWaiting()
  })
  try {
    await Promise.all([productStore.fetchActiveProduct(), fetchRoadmap(), sequenceRunStore.hydrate()])
    rehydrateWaitingFromStorage()
    try {
      const { data } = await api.taxonomyTypes.list()
      projectTypes.value = data || []
    } catch {
      console.error('[ROADMAP] Failed to load taxonomy types')
    }
  } catch (error) {
    console.error('[ROADMAP] Failed to initialize:', error)
  }
})

onUnmounted(() => {
  if (unsubRoadmap) unsubRoadmap()
  if (unsubAgentActive) unsubAgentActive()
  if (unsubProjectUpdate) unsubProjectUpdate()
  unsubHeadlessLifecycle.forEach((u) => u())
  if (unsubResync) unsubResync()
  if (waitingTimeout) clearTimeout(waitingTimeout)
  if (refetchDebounce) clearTimeout(refetchDebounce)
})

defineExpose({
  items,
  displayItems,
  foldInTasks,
  isEmptyRoadmap,
  onListReorder,
  demote,
  removeItem,
  fetchRoadmap,
  waiting,
  isPersisting,
  copyRoadmapPrompt,
  startWaiting,
  dismissWaiting,
  onAgentActive,
  onRoadmapUpdated,
  onProjectUpdated,
  buildRoadmapPrompt,
  currentPromptText,
})
</script>

