      <div class="filter-bar main-window-reveal main-window-delay-2">
        <span class="rm-product-label">
          <span class="rm-product-dot" :class="{ 'rm-product-dot--off': !activeProduct }"></span>
          {{ activeProduct ? activeProduct.name : 'Active product' }}
        </span>
        <div class="filter-spacer"></div>
        <v-switch
          v-model="foldInTasks"
          label="Fold in tasks"
          color="primary"
          density="compact"
          hide-details
          inset
          class="rm-fold-toggle"
        />
        <RoadmapPromptActions
          :is-empty="isEmptyRoadmap"
          :prompt-text="currentPromptText"
          @copy="copyRoadmapPrompt"
        />
      </div>

      <v-alert
        v-if="waiting"
        type="info"
        variant="tonal"
        density="compact"
        class="rm-waiting main-window-reveal main-window-delay-2"
        closable
        @click:close="dismissWaiting"
      >
        <div class="rm-waiting-row">
          <v-progress-circular indeterminate size="18" width="2" color="primary" class="rm-waiting-spin" />
          <span>
            Waiting for your agent… paste the copied prompt into the agent connected to this account.
            This clears automatically when your agent saves the roadmap.
          </span>
        </div>
      </v-alert>

      <v-alert
        v-if="showInsightBanner"
        type="info"
        variant="tonal"
        density="compact"
        icon="mdi-lightbulb-on-outline"
        class="rm-insight main-window-reveal main-window-delay-2"
      >
        <div class="font-weight-bold mb-1">{{ insightTitle }}</div>
        <div>{{ roadmap.summary }}</div>
      </v-alert>

      <div v-if="loading && items.length === 0" class="rm-loading">
        <v-progress-circular indeterminate color="primary" size="32" />
      </div>

      <v-alert
        v-else-if="items.length === 0"
        type="info"
        variant="tonal"
        class="main-window-reveal main-window-delay-2"
      >
        No roadmap yet. Ask your AI agent to rank this product's inactive projects and pending tasks
        (it writes the roadmap via the <code>save_roadmap</code> MCP tool), then refresh.
      </v-alert>

      <draggable
        v-else
        :model-value="displayItems"
        item-key="id"
        handle=".rm-grip"
        tag="div"
        class="rm-list main-window-reveal main-window-delay-2"
        ghost-class="rm-ghost"
        :animation="180"
        @update:model-value="onListReorder"
      >
        <template #item="{ element, index }">
          <div class="rm-row">
            <RoadmapCard
              :item="element"
              :rank="index + 1"
              :in-chain="sequenceRunStore.isProjectInActiveChain(element.project_id)"
              @convert="convertTask"
              @open="openItem"
              @demote="demote"
              @remove="removeItem"
            />
          </div>
        </template>
      </draggable>
    </template>

    <ProjectCreateEditDialog
      ref="projectDialogRef"
      v-model="showProjectDialog"
      :editing-project="editingProject"
      :active-product="activeProduct"
      :project-types="projectTypes"
      @saved="onProjectSaved"
      @clear-mission="showClearMissionDialog = true"
      @type-created="onTypeCreated"
    />

    <BaseDialog
      v-model="showClearMissionDialog"
      type="warning"
      title="Clear Mission?"
      confirm-label="Clear"
      size="sm"
      @confirm="onClearMissionConfirmed"
      @cancel="showClearMissionDialog = false"
    >
      <p>Clear the mission? It will be regenerated on next staging.</p>
    </BaseDialog>

    <TaskEditDialog
      v-model="showTaskDialog"
      :editing-task="editingTask"
      :current-task="currentTask"
      :saving="saving"
      :status-select-options="TASK_STATUS_OPTIONS"
      :task-type-options="taskTypeOptions"
      @cancel="cancelTask"
      @save="onTaskSave"
      @update:current-task="onCurrentTaskUpdate"
    />

    <BaseDialog
      v-model="showConvertConfirm"
      type="info"
      title="Convert to Project"
      icon="mdi-folder-arrow-up"
      confirm-label="Convert"
      @confirm="confirmConvert"
      @cancel="showConvertConfirm = false"
    >
      <p class="text-body-large mb-2">
        Convert task <strong>"{{ conversionItem?.title }}"</strong> to a project?
      </p>
      <p class="text-body-medium text-muted-a11y">
        This creates a new project in the viewed product from the task's title and description.
      </p>
    </BaseDialog>
  </v-container>
