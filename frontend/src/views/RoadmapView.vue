        <p class="text-body-medium text-muted-a11y mt-1">
          An AI-prioritized execution plan from this product's inactive projects and pending tasks, each scored for risk and complexity by your AI agent. Drag to reorder, or convert a task into a project. Implementation starts elsewhere — on the Projects page, or from your connected agent.
          <v-tooltip location="bottom start" max-width="600">
            <template #activator="{ props }">
              <v-icon v-bind="props" size="16" class="help-icon">mdi-help-circle-outline</v-icon>
            </template>
            <div>
              <div class="font-weight-bold mb-1">Roadmap Reference</div>
              <div class="text-body-small mb-2 text-muted-a11y">One roadmap per product</div>
              <div><span class="font-weight-medium">Rank:</span> drag the dotted grip to reorder; the new order is saved automatically and survives a refresh.</div>
              <div class="mt-1"><span class="font-weight-medium">Convert (tasks):</span> promotes the task to a project using the standard conversion.</div>
              <div class="mt-2 text-body-small">The ranking, plus each item's risk and complexity, is generated by your AI agent via the roadmap MCP tool. This page orders work; it does not launch it.</div>
            </div>
